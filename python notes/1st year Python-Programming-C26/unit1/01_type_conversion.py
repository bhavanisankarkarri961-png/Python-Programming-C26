# Python Type Conversion

# Integer to Float
a = 6
b = float(a)
print("Integer to Float:", b)

# Float to Integer
c = 6.2
d = int(c)
print("Float to Integer:", d)

# Integer to String
e = 10
f = str(e)
print("Integer to String:", f)

# Integer to Boolean
g = 1
h = bool(g)
print("Integer to Boolean:", h)

# Float to Boolean
i = 0.0
j = bool(i)
print("Float to Boolean:", j)

# String to Integer
k = "100"
l = int(k)
print("String to Integer:", l)