# Python ASCII Values

# Character to ASCII value using ord()
char_a = 'A'
ascii_a = ord(char_a)

print("Character:", char_a)
print("ASCII Value:", ascii_a)

# Another character
char_b = 'z'
ascii_b = ord(char_b)

print("Character:", char_b)
print("ASCII Value:", ascii_b)

# ASCII value to character using chr()
number = 104
character = chr(number)

print("ASCII Value:", number)
print("Character:", character)